def _rename_stage_for_display(value):
    """Translate stage labels for user-facing display.
    Accepts strings, dicts (renames string values), lists (recurses), or anything
    else (returned unchanged).
    """
    if isinstance(value, str):
        result = value
        for old, new in _STAGE_DISPLAY_RENAMES:
            result = result.replace(old, new)
        return result
    if isinstance(value, dict):
        return {k: _rename_stage_for_display(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_rename_stage_for_display(item) for item in value]
    return value


