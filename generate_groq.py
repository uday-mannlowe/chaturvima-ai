# ─────────────────────────────────────────────────────────────────────────────
# REPORT-TYPE → DEDICATED MODEL MAPPING
#
# Key insight: each report type is ALWAYS generated by ONE specific model,
# regardless of which dimension the overall input is.
#
#   employee report  → MODEL_NAME_1D  (fast, lighter model is fine)
#   boss report      → MODEL_NAME_2D
#   team report      → MODEL_NAME_3D
#   org report       → MODEL_NAME_4D
#
# Higher dimensions use their matching report type by default. If multiple
# report types are requested, they are generated sequentially to avoid bursts.
# ─────────────────────────────────────────────────────────────────────────────
MODEL_BY_REPORT_TYPE_DEDICATED = {
    "employee":     MODEL_NAME_1D,   # always use 1D model for employee report
    "boss":         MODEL_NAME_2D,   # always use 2D model for boss report
    "boss_overview": MODEL_NAME_2D,  # always use 2D model for boss overview report
    "team":         MODEL_NAME_3D,   # always use 3D model for team report
    "organization": MODEL_NAME_4D,   # always use 4D model for org report
}

REPORT_TYPE_TO_DIMENSION_HINT = {
    "employee": "1D",
    "boss": "2D",
    "team": "3D",
    "organization": "4D",
}

MODEL_BY_REPORT_TYPE = {
    report_type: MODEL_BY_DIMENSION[dim]
    for report_type, dim in REPORT_TYPE_TO_DIMENSION_HINT.items()
}

GLOBAL_MODEL_FALLBACKS = [
    m.strip()
    for m in os.getenv("GROQ_MODEL_FALLBACKS", "").split(",")
    if m.strip()
]


def _dedupe_models(models: List[str]) -> List[str]:
    unique: List[str] = []
    seen = set()
    for model in models:
        cleaned = (model or "").strip()
        if not cleaned or cleaned in seen:
            continue
        unique.append(cleaned)
        seen.add(cleaned)
    return unique


GROQ_ALLOWED_MODELS = _dedupe_models(
    [
        m.strip()
        for m in os.getenv("GROQ_ALLOWED_MODELS", "").split(",")
        if m.strip()
    ]
)
_GROQ_ALLOWED_MODEL_KEYS = {model.lower() for model in GROQ_ALLOWED_MODELS}


def _filter_allowed_models(models: List[str]) -> List[str]:
    deduped = _dedupe_models(models)
    if not _GROQ_ALLOWED_MODEL_KEYS:
        return deduped

    allowed = [
        model
        for model in deduped
        if model.lower() in _GROQ_ALLOWED_MODEL_KEYS
    ]
    return allowed or GROQ_ALLOWED_MODELS.copy()


def _resolve_model_candidates(
    dimension: Any = None,
    report_type: str = "",
    start_offset: int = 0,
) -> List[str]:
    """
    Return an ordered list of model candidates.
    Priority:
    1) report-type model (if available),
    2) explicit dimension model,
    3) all configured dimension models,
    4) global fallback list,
    5) default model.
    """
    normalized_dim = None
    if isinstance(dimension, int) and 1 <= dimension <= 4:
        normalized_dim = f"{dimension}D"
    elif isinstance(dimension, str):
        raw = dimension.upper().strip()
        if raw in {"1D", "2D", "3D", "4D"}:
            normalized_dim = raw
        elif raw in {"1", "2", "3", "4"}:
            normalized_dim = f"{raw}D"

    report_key = (report_type or "").strip().lower()

    candidates: List[str] = []
    if report_key in MODEL_BY_REPORT_TYPE:
        candidates.append(MODEL_BY_REPORT_TYPE[report_key])

    if normalized_dim in MODEL_BY_DIMENSION:
        candidates.append(MODEL_BY_DIMENSION[normalized_dim])

    hinted_dim = REPORT_TYPE_TO_DIMENSION_HINT.get(report_key)
    if hinted_dim in MODEL_BY_DIMENSION:
        candidates.append(MODEL_BY_DIMENSION[hinted_dim])

    for dim in ("1D", "2D", "3D", "4D"):
        candidates.append(MODEL_BY_DIMENSION[dim])

    candidates.extend(GLOBAL_MODEL_FALLBACKS)
    candidates.append(MODEL_NAME)

    deduped = _filter_allowed_models(candidates)
    if not deduped:
        deduped = _filter_allowed_models([MODEL_NAME]) or [MODEL_NAME]

    if start_offset and len(deduped) > 1:
        idx = abs(int(start_offset)) % len(deduped)
        deduped = deduped[idx:] + deduped[:idx]

    return deduped


def _is_rate_limited_error(err: str) -> bool:
    lowered = (err or "").lower()
    return (
        "429" in lowered
        or "rate_limit_exceeded" in lowered
        or "too many requests" in lowered
    )


def _extract_retry_wait_seconds(err: str, attempt: int) -> float:
    lowered = (err or "").lower()
    match = re.search(r"try again in (\d+(?:\.\d+)?)(ms|s)", lowered)
    if match:
        value = float(match.group(1))
        unit = match.group(2)
        return value / 1000.0 if unit == "ms" else value

    retry_after = re.search(r"retry[- ]after[: ]+(\d+(?:\.\d+)?)", lowered)
    if retry_after:
        return float(retry_after.group(1))

    return min(12 * attempt, 90)


def _positive_int_env(name: str, default: int) -> int:
    try:
        return max(1, int(os.getenv(name, str(default))))
    except (TypeError, ValueError):
        return max(1, int(default))


def _non_negative_float_env(name: str, default: float) -> float:
    try:
        return max(0.0, float(os.getenv(name, str(default))))
    except (TypeError, ValueError):
        return max(0.0, float(default))


def _non_negative_int_env(name: str, default: int) -> int:
    try:
        return max(0, int(os.getenv(name, str(default))))
    except (TypeError, ValueError):
        return max(0, int(default))


# ─────────────────────────────────────────────────────────────────────────────
# OUTPUT-SIZE ESTIMATION (used only to skip a single call that cannot fit)
#
# Calibrated by generating one report of each type with reasoning disabled:
#
#   report type     specs   words   words/spec   tokens (x1.4)   fits 4000?
#   organization      13     3,298         254           4,617        no
#   team              14     3,880         277           5,432        no
#   employee          10     3,445         344           4,823        no
#   boss              14     4,939         353           6,915        no
#
# Sections land at 254-353 words each regardless of their `target_words`,
# because the prompt rule "3-4 paragraphs, 70-120 words each" dominates the
# per-section target. 300 sits inside that observed range, so no section is
# counted as smaller than that.
#
# NOTE: an earlier calibration used 250, taken from reports generated *before*
# reasoning was disabled. Those reports were smaller because reasoning tokens
# were consuming the budget that content should have used, so 250 under-counted
# and let the 1D employee report attempt a single call that then truncated at
# 4,000 tokens and was discarded (measured: 3 calls / 91.9s instead of 2 / 48s).
# ─────────────────────────────────────────────────────────────────────────────
_JSON_REPORT_MIN_WORDS_PER_SECTION = _positive_int_env(
    "JSON_REPORT_MIN_WORDS_PER_SECTION", 300
)
_JSON_REPORT_TOKENS_PER_WORD = _non_negative_float_env(
    "JSON_REPORT_TOKENS_PER_WORD", 1.4
)
_JSON_REPORT_SKIP_FUTILE_PRIMARY = os.getenv(
    "JSON_REPORT_SKIP_FUTILE_PRIMARY", "true"
).lower() in {"1", "true", "yes", "on"}


def _estimate_report_output_tokens(specs: 'List[SectionSpec]', target_words_fn) -> int:
    """
    Estimate the output tokens a full single-call report would need.

    Returns 0 when there are no specs to measure, which callers must treat as
    "unknown" rather than "small".
    """
    if not specs:
        return 0
    words = sum(
        max(int(target_words_fn(spec)), _JSON_REPORT_MIN_WORDS_PER_SECTION)
        for spec in specs
    )
    return int(words * _JSON_REPORT_TOKENS_PER_WORD)


_GROQ_MAX_IN_FLIGHT = _positive_int_env(
    "GROQ_MAX_IN_FLIGHT",
    getattr(Config, "GROQ_MAX_IN_FLIGHT", 1),
)
_GROQ_REQUEST_SPACING_SECONDS = _non_negative_float_env(
    "GROQ_REQUEST_SPACING_SECONDS",
    getattr(
        Config,
        "GROQ_REQUEST_SPACING_SECONDS",
        60.0 / max(getattr(Config, "GROQ_RATE_LIMIT_PER_MINUTE", 30), 1),
    ),
)
_GROQ_MAX_RETRIES = _positive_int_env(
    "GROQ_MAX_RETRIES",
    getattr(Config, "GROQ_MAX_RETRIES", 3),
)
_GROQ_CALL_SEMAPHORE = threading.BoundedSemaphore(_GROQ_MAX_IN_FLIGHT)
_GROQ_PACE_LOCK = threading.Lock()
_GROQ_LAST_REQUEST_AT = 0.0


def _pace_groq_request(request_label: str = "request") -> None:
    if _GROQ_REQUEST_SPACING_SECONDS <= 0:
        return

    import time as _time

    global _GROQ_LAST_REQUEST_AT

    while True:
        with _GROQ_PACE_LOCK:
            now = _time.monotonic()
            wait = _GROQ_REQUEST_SPACING_SECONDS - (now - _GROQ_LAST_REQUEST_AT)
            if wait <= 0:
                _GROQ_LAST_REQUEST_AT = now
                return

        print(f"Throttling Groq {request_label}: waiting {wait:.1f}s")
        _time.sleep(wait)


# ─────────────────────────────────────────────────────────────────────────────
# REASONING BUDGET
#
# deepseek-v4-flash is a reasoning model: it emits `reasoning_content` that is
# billed and counted against `max_tokens`, but is NOT part of `message.content`.
# Measured on a single-section refill prompt (max_tokens=2000):
#
#   reasoning_effort  reasoning_chars  completion_tokens  finish_reason
#   (unset)                     7,902              2,000  length   <- content cut off
#   (unset, rerun)                308                424  stop
#   "none"                            0                422  stop
#
# The size of the reasoning block varied between 308 and 9,910 characters across
# runs of the same prompt. When it ran long it consumed the whole token budget,
# the JSON body was truncated mid-string, the parser recovered nothing, and the
# section was discarded and regenerated — which is what made report generation
# both slow and unreliable (a 2D run produced 3 of 14 sections in 461s).
#
# These prompts ask for structured narrative from data that is already supplied;
# they do not benefit from extended chain-of-thought. Set
# DEEPSEEK_REASONING_EFFORT="" to send no parameter at all and restore the old
# behaviour.
# ─────────────────────────────────────────────────────────────────────────────
_DEEPSEEK_REASONING_EFFORT = os.getenv("DEEPSEEK_REASONING_EFFORT", "none").strip()
_REASONING_EFFORT_SUPPORTED = True


def _create_groq_chat_completion(client: OpenAI, request_label: str = "request", **kwargs: Any):
    global _REASONING_EFFORT_SUPPORTED

    with _GROQ_CALL_SEMAPHORE:
        _pace_groq_request(request_label)
        if _DEEPSEEK_REASONING_EFFORT and _REASONING_EFFORT_SUPPORTED:
            try:
                return client.chat.completions.create(
                    reasoning_effort=_DEEPSEEK_REASONING_EFFORT, **kwargs
                )
            except Exception as exc:
                # Only treat this as "parameter unsupported" — never swallow a
                # real API failure, which must still propagate to the caller's
                # retry/fallback logic.
                if "reasoning_effort" not in str(exc):
                    raise
                _REASONING_EFFORT_SUPPORTED = False
                print(
                    f"reasoning_effort rejected by the API ({exc}); "
                    f"continuing without it for the rest of this process."
                )
        return client.chat.completions.create(**kwargs)


def _call_groq_with_model_fallback(
    messages: List[Dict[str, str]],
    temperature: float,
    max_tokens: int,
    dimension: Any = None,
    report_type: str = "",
    start_offset: int = 0,
    max_retries: int = _GROQ_MAX_RETRIES,
    request_label: str = "request",
) -> Tuple[str, str]:
    import random
    import time as _time

    candidates = _resolve_model_candidates(
        dimension=dimension,
        report_type=report_type,
        start_offset=start_offset,
    )
    last_exc = None

    for attempt in range(1, max_retries + 1):
        attempt_hit_rate_limit = False

        for model in candidates:
            try:
                client = create_groq_client()
                response = _create_groq_chat_completion(
                    client,
                    request_label=f"{request_label} [{model}]",
                    model=model,
                    messages=messages,
                    temperature=temperature,
                    max_tokens=max_tokens,
                )
                return response.choices[0].message.content.strip(), model
            except Exception as exc:
                last_exc = exc
                err = str(exc)
                if _is_rate_limited_error(err):
                    attempt_hit_rate_limit = True
                    print(f"⏳ {request_label}: model '{model}' rate-limited; trying next model.")
                    continue

                # Non-rate-limit failure on this model: try other models first.
                print(f"⚠️ {request_label}: model '{model}' failed ({err}); trying next model.")

        if not attempt_hit_rate_limit:
            if last_exc is not None:
                raise last_exc
            raise RuntimeError(f"{request_label} failed with no response and no exception.")

        wait = _extract_retry_wait_seconds(str(last_exc), attempt) + random.uniform(1, 4)
        print(
            f"⏳ {request_label}: all model candidates exhausted "
            f"(attempt {attempt}/{max_retries}), waiting {wait:.1f}s…"
        )
        _time.sleep(wait)

    raise RuntimeError(
        f"{request_label} failed after {max_retries} attempts. Last error: {last_exc}"
    )

# RAG SYSTEM CLASS

class BehavioralStagesRAG:
    """
    RAG system for retrieving behavioral stage definitions and context.
    """
    
    def __init__(self, vector_db_path: str = "vector_db/behavioral_stages_semantic"):
        print("🔄 Loading RAG system...")
        self.embeddings = HuggingFaceEmbeddings(
            model_name="sentence-transformers/all-MiniLM-L6-v2"
        )
        
        try:
            self.vectorstore = FAISS.load_local(
                vector_db_path,
                self.embeddings,
                allow_dangerous_deserialization=True
            )
            print(f"✅ RAG system loaded from {vector_db_path}")
        except Exception as e:
            print(f"⚠️ Warning: Could not load vector store: {e}")
            print("   RAG will be disabled for this session.")
            self.vectorstore = None
    
    def retrieve_stage_context(self, stage_name: str, k: int = 2) -> str:
        """
        Retrieve context for a specific behavioral stage.
        
        Args:
            stage_name: Name of the stage (e.g., "Honeymoon Stage")
            k: Number of chunks to retrieve
            
        Returns:
            Formatted context string
        """
        if self.vectorstore is None:
            return ""
        
        query = f"{stage_name} characteristics and behaviors"
        docs = self.vectorstore.similarity_search(query, k=k)
        
        context_parts = []
        for doc in docs:
            context_parts.append(
                f"[{doc.metadata.get('section_name', 'Unknown')}]\n{doc.page_content}"
            )
        
        return "\n\n".join(context_parts)
    
    def retrieve_multi_stage_context(self, stages: List[str], k_per_stage: int = 2) -> str:
        """
        Retrieve context for multiple stages.
        
        Args:
            stages: List of stage names
            k_per_stage: Number of chunks per stage
            
        Returns:
            Combined context string
        """
        if self.vectorstore is None:
            return ""
        
        all_context = []
        for stage in stages:
            context = self.retrieve_stage_context(stage, k=k_per_stage)
            if context:
                all_context.append(f"=== {stage.upper()} ===\n{context}")
        
        return "\n\n".join(all_context)
    
    def retrieve_behavioral_indicators(self, behavior_description: str, k: int = 3) -> str:
        """
        Retrieve relevant behavioral indicators based on description.
        
        Args:
            behavior_description: Description of observed behavior
            k: Number of chunks to retrieve
            
        Returns:
            Formatted context string
        """
        if self.vectorstore is None:
            return ""
        
        docs = self.vectorstore.similarity_search(behavior_description, k=k)
        
        context_parts = []
        for doc in docs:
            stage = doc.metadata.get('stage', 'Unknown Stage')
            section = doc.metadata.get('section_name', 'Unknown Section')
            context_parts.append(
                f"[{stage} - {section}]\n{doc.page_content}"
            )
        
        return "\n\n".join(context_parts)


